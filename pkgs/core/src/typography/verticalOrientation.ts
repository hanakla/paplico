/**
 * Whether vertical writing keeps `char` upright rather than laying it on its
 * side, judged by its first code point.
 */
export function isUprightInVertical(char: string): boolean {
	const code = char.codePointAt(0);
	if (code === undefined) return false;
	let low = 0;
	let high = UPRIGHT_RANGES.length - 1;
	while (low <= high) {
		const mid = (low + high) >> 1;
		const [start, end] = UPRIGHT_RANGES[mid];
		if (code < start) high = mid - 1;
		else if (code > end) low = mid + 1;
		else return true;
	}
	return false;
}
