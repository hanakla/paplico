/**
 * Generates pkgs/core/src/color/cmykPressTable.generated.ts: a grid of sRGB
 * colors sampled from a CMYK profile, which the core interpolates to convert
 * CMYK that comes without a profile.
 *
 * The table in the repository was sampled from FOGRA39L_coated.icc of the
 * CTAN colorprofiles package (https://ctan.org/pkg/colorprofiles), under the
 * zlib/libpng license. The profile is not part of the repository.
 *
 * Usage: yarn tsx scripts/gen-cmyk-press-table.ts <FOGRA39L_coated.icc> <sRGB.icc>
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import jsce from "jscolorengine";

/** Points per ink axis, from no ink to full ink. */
const GRID_POINTS = 9;

const OUTPUT = resolve(
	import.meta.dirname,
	"../pkgs/core/src/color/cmykPressTable.generated.ts",
);

const [cmykPath, rgbPath] = process.argv.slice(2);
if (!cmykPath || !rgbPath) {
	throw new Error("Usage: gen-cmyk-press-table.ts <cmyk.icc> <srgb.icc>");
}

const cmykProfile = new jsce.Profile();
cmykProfile.loadBinary(new Uint8Array(readFileSync(cmykPath)));
const rgbProfile = new jsce.Profile();
rgbProfile.loadBinary(new Uint8Array(readFileSync(rgbPath)));
if (!cmykProfile.loaded || !rgbProfile.loaded) {
	throw new Error("Failed to load the ICC profiles");
}

// Relative colorimetric with black point compensation, the conversion
// design applications use by default.
const transform = new jsce.Transform({ dataFormat: "int8", BPC: true });
transform.create(cmykProfile, rgbProfile, jsce.eIntent.relative);

const step = (index: number) => Math.round((index * 255) / (GRID_POINTS - 1));
const inks = new Uint8Array(GRID_POINTS ** 4 * 4);
let at = 0;
for (let c = 0; c < GRID_POINTS; c++) {
	for (let m = 0; m < GRID_POINTS; m++) {
		for (let y = 0; y < GRID_POINTS; y++) {
			for (let k = 0; k < GRID_POINTS; k++) {
				inks.set([step(c), step(m), step(y), step(k)], at);
				at += 4;
			}
		}
	}
}
const rgb = transform.transformArray(
	inks,
	false,
	false,
	false,
	GRID_POINTS ** 4,
	"int8",
);

